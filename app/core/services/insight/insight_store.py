    async def get_insight_stats(self, user_uid: UserUID) -> Result[dict[str, Any]]:
        """
        Get statistics about a user's insights.

        ``total``, ``dismissed``, ``actioned``, ``action_rate`` and ``domains`` are
        all-time; ``active``, ``critical`` and ``high`` count the active set.

        Args:
            user_uid: User identifier

        Returns:
            Result with insight statistics
        """
        try:
            result = await self.backend.get_insight_stats(user_uid)

            if result.is_error:
                self.logger.error(f"Error getting insight stats: {result.error}")
                return Result.fail(
                    Errors.database(
                        message=f"Failed to get insight stats: {result.error}",
                        operation="get_insight_stats",
                    )
                )

            if result.value:
                record = result.value[0]
                return Result.ok(
                    {
                        "total_insights": record["total_insights"],
                        "active_insights": record["active_insights"],
                        "dismissed_insights": record["dismissed_insights"],
                        "actioned_insights": record["actioned_insights"],
                        "critical_insights": record["critical_insights"],
                        "high_insights": record["high_insights"],
                        "domains": record["domains"],
                        "action_rate": (
                            record["actioned_insights"] / record["total_insights"]
                            if record["total_insights"] > 0
                            else 0.0
                        ),
                    }
                )

            return Result.ok(
                {
                    "total_insights": 0,
                    "active_insights": 0,
                    "dismissed_insights": 0,
                    "actioned_insights": 0,
                    "critical_insights": 0,
                    "high_insights": 0,
                    "domains": [],
                    "action_rate": 0.0,
                }
            )

        except NEO4J_EXCEPTIONS as e:
            self.logger.error(f"Error getting insight stats: {e}", exc_info=True)
            return Result.fail(
                Errors.database(
                    message=f"Failed to get insight stats: {e}",
                    operation="get_insight_stats",
                )
            )

