    async def get_type_distribution_chart(self, user_uid: UserUID) -> Result[ChartJsConfig]:
        """Build Chart.js doughnut config for insight type distribution.

        Counts the whole active set per type, the largest first, a tie in name
        order. Each slice takes its type's own colour (``InsightType.get_color()``),
        so a type looks the same whatever its place; a stored type outside the enum
        is a failed read.

        Args:
            user_uid: User identifier

        Returns:
            Result with Chart.js doughnut config
        """
        result = await self.count_active_insights_by(user_uid, InsightField.INSIGHT_TYPE)
        if result.is_error:
            return Result.fail(result)

        sorted_types = sorted(result.value.items(), key=_by_count_then_name)
        unknown = [t for t, _ in sorted_types if t not in InsightType]
        if unknown:
            return Result.fail(
                Errors.database(
                    message=f"Stored insight types outside InsightType: {unknown}",
                    operation="get_type_distribution_chart",
                )
            )
        labels = [t.replace("_", " ").title() for t, _ in sorted_types]

        return Result.ok(
            {
                "type": "doughnut",
                "data": {
                    "labels": labels,
                    "datasets": [
                        {
                            "label": "Insights by Type",
                            "data": [count for _, count in sorted_types],
                            "backgroundColor": [
                                rgba(InsightType(t).get_color(), ChartColor.FILL_ALPHA)
                                for t, _ in sorted_types
                            ],
                        }
                    ],
                },
                "options": {
                    "responsive": True,
                    "plugins": {
                        "legend": {"position": "right"},
                        "title": {"display": True, "text": "Insights by Type"},
                    },
                },
            }
        )

    async def get_action_rate_chart(self, user_uid: UserUID) -> Result[ChartJsConfig]:
        """Build Chart.js gauge-style doughnut config for action rate.

        Uses insight stats to show percentage of actioned vs not actioned.

        Args:
            user_uid: User identifier

        Returns:
            Result with Chart.js doughnut config (half-circle gauge)
        """
        stats_result = await self.get_insight_stats(user_uid)
        if stats_result.is_error:
            return Result.fail(stats_result)

        stats = stats_result.value
        action_rate = stats.get("action_rate", 0) * 100
        remaining_rate = 100 - action_rate

        return Result.ok(
            {
                "type": "doughnut",
                "data": {
                    "labels": ["Actioned", "Not Actioned"],
                    "datasets": [
                        {
                            "label": "Action Rate",
                            "data": [action_rate, remaining_rate],
                            "backgroundColor": [
                                rgba(ChartColor.ACTIONED, ChartColor.FILL_ALPHA),
                                rgba(ChartColor.NOT_ACTIONED, ChartColor.MUTED_ALPHA),
                            ],
                        }
                    ],
                },
                "options": {
                    "responsive": True,
                    "circumference": 180,
                    "rotation": -90,
                    "plugins": {
                        "legend": {"position": "bottom"},
                        "title": {"display": True, "text": f"Action Rate: {action_rate:.1f}%"},
                    },
                },
            }
        )

    async def count_active_insights_by(
        self, user_uid: UserUID, field: InsightField
    ) -> Result[dict[str, int]]:
        """Count a user's whole active set by one insight field.

        Backend: ``InsightBackend.count_active_insights_by`` — a grouped count,
        so no page caps it.

        Args:
            user_uid: User identifier
            field: The property to group by — impact, domain or insight type

        Returns:
            Result with a dict mapping each value present to its count
            (e.g. ``{"habits": 3, "tasks": 5}`` by domain)
        """
        try:
            result = await self.backend.count_active_insights_by(user_uid, field)
        except NEO4J_EXCEPTIONS as e:
            self.logger.error(f"Error counting active insights by {field}: {e}", exc_info=True)
            return Result.fail(
                Errors.database(
                    message=f"Failed to count active insights: {e}",
                    operation="count_active_insights_by",
                )
            )
        if result.is_error:
            self.logger.error(f"Error counting active insights by {field}: {result.error}")
            return Result.fail(result)

        return Result.ok({record["value"]: int(record["count"]) for record in result.value})
